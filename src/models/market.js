Shop.hasMany(Product, { as: 'products', foreignKey: 'shopId' });
Product.belongsTo(Shop, { as: 'shop', foreignKey: 'shopId' });
Product.hasMany(ProductVariant, { as: 'variants', foreignKey: 'productId' });
ProductVariant.belongsTo(Product, { as: 'product', foreignKey: 'productId' });

module.exports = { Shop, Product, ProductVariant, ProductPhoto, InventoryMovement, SavedItem };
