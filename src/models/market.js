'use strict';

/**
 * M12 Market models, step 1 (migration 20261029000004-create-market): shops, products,
 * product_variants, product_photos, inventory_movements, saved_items. index.js re-exports them.
 */
const { DataTypes, Model } = require('sequelize');
const { sequelize } = require('../db');
const { uuid7 } = require('../common/uuid7');
const { toPoisha } = require('../common/money');

const id = { type: DataTypes.UUID, primaryKey: true, defaultValue: () => uuid7() };
const req = (type) => ({ type, allowNull: false });
const by = { createdBy: DataTypes.UUID, updatedBy: DataTypes.UUID };
const num = (field, type, allowNull = false) => ({
  type,
  allowNull,
  get() {
    const v = this.getDataValue(field);
    return v === null || v === undefined ? null : Number(v);
  },
});
const poisha = (field, allowNull = false) => ({
  type: DataTypes.BIGINT,
  allowNull,
  get() {
    const v = this.getDataValue(field);
    return v === null || v === undefined ? null : toPoisha(v);
  },
});
const STATUSES = ['draft', 'pending_review', 'changes_requested', 'live', 'paused', 'rejected', 'withdrawn', 'suspended', 'removed'];
const review = () => ({
  status: { type: DataTypes.ENUM(...STATUSES), allowNull: false, defaultValue: 'draft' },
  editStatus: DataTypes.ENUM('draft', 'pending_review', 'changes_requested', 'rejected'),
  liveVersion: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
  liveSnapshot: DataTypes.JSON,
  currentSubmissionId: DataTypes.UUID,
  reviewReasonCode: DataTypes.STRING(40),
  reviewReasonText: DataTypes.STRING(500),
  firstLiveAt: DataTypes.DATE(3),
  statusChangedAt: DataTypes.DATE(3),
});

class Shop extends Model {}
Shop.init(
  {
    id,
    ownerId: req(DataTypes.UUID),
    shopType: req(DataTypes.ENUM('sports_gear', 'supplements', 'gym_gear')),
    name: req(DataTypes.STRING(80)),
    slug: req(DataTypes.STRING(96)),
    areaId: req(DataTypes.UUID),
    addressLine: req(DataTypes.STRING(200)),
    lat: num('lat', DataTypes.DECIMAL(9, 6), true),
    lng: num('lng', DataTypes.DECIMAL(9, 6), true),
    about: DataTypes.TEXT,
    ...review(),
    lowStockThreshold: req(DataTypes.SMALLINT),
    autoHideOutOfStock: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: true },
    mtoDaysDefault: req(DataTypes.SMALLINT),
    ratingAvg: num('ratingAvg', DataTypes.DECIMAL(3, 2), true),
    ratingCount: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
    ...by,
  },
  { sequelize, modelName: 'Shop', tableName: 'shops' }
);

class Product extends Model {}
Product.init(
  {
    id,
    shopId: req(DataTypes.UUID),
    itemTypeId: req(DataTypes.UUID),
    title: req(DataTypes.STRING(120)),
    slug: req(DataTypes.STRING(140)),
    brand: DataTypes.STRING(60),
    description: DataTypes.TEXT,
    specs: { type: DataTypes.JSON, allowNull: false, defaultValue: {} },
    basePricePoisha: poisha('basePricePoisha'),
    isMto: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
    mtoDays: DataTypes.SMALLINT,
    maxQtyPerOrder: req(DataTypes.SMALLINT),
    importer: DataTypes.STRING(120),
    bstiRegNo: DataTypes.STRING(60),
    ...review(),
    visibility: { type: DataTypes.ENUM('visible', 'hidden_oos'), allowNull: false, defaultValue: 'visible' },
    publicTitle: DataTypes.STRING(120),
    publicItemTypeId: DataTypes.UUID,
    publicPriceFromPoisha: poisha('publicPriceFromPoisha', true),
    publicPriceToPoisha: poisha('publicPriceToPoisha', true),
    views: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
    ...by,
  },
  { sequelize, modelName: 'Product', tableName: 'products' }
);

class ProductVariant extends Model {}
ProductVariant.init(
  {
    id,
    productId: req(DataTypes.UUID),
    shopId: req(DataTypes.UUID),
    sku: DataTypes.STRING(40),
    attributes: { type: DataTypes.JSON, allowNull: false, defaultValue: {} },
    priceOverridePoisha: poisha('priceOverridePoisha', true),
    onHand: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
    held: { type: DataTypes.INTEGER, allowNull: false, defaultValue: 0 },
    // Generated by the database (on_hand − held); never written.
    available: { type: DataTypes.INTEGER, allowNull: true },
    lowAlertedAt: DataTypes.DATE(3),
    expiryDate: DataTypes.DATEONLY,
    batchNo: DataTypes.STRING(40),
    saleBlocked: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
    status: { type: DataTypes.ENUM('active', 'retired'), allowNull: false, defaultValue: 'active' },
    retiredAt: DataTypes.DATE(3),
    sort: { type: DataTypes.SMALLINT, allowNull: false, defaultValue: 0 },
    ...by,
  },
  {
    sequelize,
    modelName: 'ProductVariant',
    tableName: 'product_variants',
    hooks: {
      // available is GENERATED ALWAYS: keep it out of every INSERT and UPDATE.
      beforeSave: (v, options) => {
        if (options.fields) options.fields = options.fields.filter((f) => f !== 'available');
      },
      beforeBulkCreate: (rows, options) => {
        if (options.fields) options.fields = options.fields.filter((f) => f !== 'available');
      },
    },
  }
);

class ProductPhoto extends Model {}
